#!/usr/bin/env python3
"""Build the students' pretest page data from the pretest banks: questions only, never an answer.

  python quizes/pretest/build_page.py           write blockchain-course/assets/labs/pretest/items.js
  python quizes/pretest/build_page.py --check   fail if items.js is stale or holds any answer

The page (blockchain-course/assets/labs/pretest/index.html) is on the public course site. It shows these items,
keeps a student's answers in their browser and sends them to the instructor by email; mark_pretest.py, beside
this file, marks the replies against the banks. So items.js carries each stem and each option's text, but no
correct answer, explanation, answer key, concept or source. Each option gets an id made from a hash of its
text, and the options are listed in id order, so neither the id nor the position tells the right one.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
BANKS = {1: HERE / "pretest_week1-quiz-bank.json", 2: HERE / "pretest_week2-quiz-bank.json"}
OUT = REPO / "blockchain-course" / "assets" / "labs" / "pretest" / "items.js"
HEADER = ("/* Generated by quizes/pretest/build_page.py from the pretest banks: do not edit, run the script.\n"
          "   Questions only: no answer, explanation or answer key is in this file. */\n")


def option_id(qid: str, text: str) -> str:
    """Six hex digits of a hash of the item id and the option's text: stable while the text stays the same."""
    return hashlib.sha256(f"{qid}\n{text}".encode("utf-8")).hexdigest()[:6]


def blocks(stem: str) -> list[dict[str, str]]:
    """A stem as paragraphs and code blocks; the page draws `inline code` inside a paragraph itself."""
    out = []
    for n, chunk in enumerate(re.split(r"^```[^\n]*$", stem.strip(), flags=re.M)):
        if n % 2:  # inside a fence: keep the code's own lines and indents
            out.append({"code": chunk.strip("\n")})
            continue
        out += [{"p": " ".join(part.split())} for part in re.split(r"\n\s*\n", chunk) if part.strip()]
    return [b for b in out if b.get("code") or b.get("p")]


def load_banks() -> dict[int, dict]:
    return {week: json.loads(path.read_text(encoding="utf-8")) for week, path in BANKS.items()}


def page_items(banks: dict[int, dict]) -> list[dict]:
    items = []
    for week, bank in banks.items():
        order = [qid for day in sorted(bank["metadata"]["days"], key=int) for qid in bank["metadata"]["days"][day]]
        by_id = {q["id"]: q for q in bank["questions"]}
        for qid in order:
            q = by_id[qid]
            item = {"id": qid, "week": week, "day": q["day"], "stem": blocks(q["question_stem"])}
            if q["question_type"] == "multiple_choice":
                texts = [q["correct_answer"], *q["incorrect_answers"]]
                item["options"] = sorted(({"id": option_id(qid, t), "text": t} for t in texts),
                                         key=lambda o: o["id"])
            else:
                item["written"] = True
            items.append(item)
    return items


def form_id(items: list[dict]) -> str:
    """One short id for this exact set of items and options, so the marker can tell an older form."""
    shape = [[i["id"], [o["id"] for o in i.get("options", [])], i["stem"]] for i in items]
    return hashlib.sha256(json.dumps(shape, sort_keys=True).encode("utf-8")).hexdigest()[:8]


def render(banks: dict[int, dict]) -> str:
    items = page_items(banks)
    data = {"form": form_id(items), "items": items}
    return HEADER + "window.PRETEST = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n"


def leaks(text: str, banks: dict[int, dict]) -> list[str]:
    """Every explanation, answer-key point or source that appears in the page data (none may)."""
    found = []
    flat = " ".join(text.split())
    for bank in banks.values():
        for q in bank["questions"]:
            secret = [("explanation", q.get("explanation", "")), ("post_test note", q.get("post_test", "")),
                      ("concept name", f'"{q["concept"]["name"]}"')]
            secret += [("answer-key point", point) for point in q.get("answer_key", [])]
            secret += [("source slide", s["slide"]) for s in q.get("sources", []) if len(s["slide"]) > 30]
            for label, value in secret:
                value = " ".join(value.split())
                if len(value) > 12 and value in flat:
                    found.append(f"{q['id']}: items.js holds its {label}")
    if re.search(r'"(correct|answer|explanation|answer_key|correct_answer)"\s*:', text):
        found.append("items.js has an answer field")
    return found


def check() -> list[str]:
    banks = load_banks()
    want = render(banks)
    errors = leaks(want, banks)
    if not OUT.is_file():
        errors.append(f"{OUT.relative_to(REPO).as_posix()} is missing: run python quizes/pretest/build_page.py")
    else:
        have = OUT.read_text(encoding="utf-8")
        errors += leaks(have, banks)
        if have.replace("\r\n", "\n") != want:
            errors.append(f"{OUT.relative_to(REPO).as_posix()} is stale: run python quizes/pretest/build_page.py")
    return errors


def main(argv: list[str]) -> int:
    if "--check" in argv:
        errors = check()
        for e in errors:
            print(f"FAIL: {e}")
        print("Pretest page OK." if not errors else f"Pretest page: {len(errors)} failure(s).")
        return 1 if errors else 0
    banks = load_banks()
    text = render(banks)
    problems = leaks(text, banks)
    if problems:
        for p in problems:
            print(f"FAIL: {p}")
        return 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO).as_posix()} ({len(page_items(banks))} items)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
