def _arcade_state_payload(state: dict) -> dict:
    consumed = []
    for key, item in (state.get("consumedSessions") or {}).items():
        public = {k: v for k, v in item.items() if k != "token"}
        public["key"] = key
        consumed.append(public)
    score_attempts = []
    for key, item in (state.get("scoreSubmissions") or {}).items():
        public = {k: v for k, v in item.items() if k != "token"}
        public["key"] = key
        score_attempts.append(public)
    return {
        "ok": True,
        "consumedSessions": sorted(consumed, key=lambda item: str(item.get("issuedAt") or "")),
        "recentSessions": [
            {k: v for k, v in item.items() if k != "token"}
            for item in (state.get("recentSessions") or [])[-40:]
        ],
        "scoreSubmissions": sorted(score_attempts, key=lambda item: str(item.get("validatedAt") or "")),
        "recentScoreAttempts": [
            {k: v for k, v in item.items() if k != "token"}
            for item in (state.get("recentScoreAttempts") or [])[-60:]
        ],
    }


def _decode_arcade_session_log(receipt: dict, vault_address: str) -> Optional[dict]:
    for log in receipt.get("logs") or []:
        if _normalize_address(log.get("address")) != vault_address:
            continue
        topics = log.get("topics") if isinstance(log.get("topics"), list) else []
        if len(topics) < 3 or str(topics[0]).lower() != _ARCADE_SESSION_STARTED_TOPIC:
            continue
        player = _normalize_address("0x" + str(topics[1])[-40:])
        game_id = _hex_int(topics[2])
        data = str(log.get("data") or "0x")[2:]
        if len(data) < 128:
            continue
        nonce = int(data[0:64], 16)
        timestamp = int(data[64:128], 16)
        return {
            "player": player,
            "gameId": game_id,
            "nonce": nonce,
            "timestamp": timestamp,
            "txHash": str(log.get("transactionHash") or receipt.get("transactionHash") or "").lower(),
            "blockNumber": _hex_int(log.get("blockNumber") or receipt.get("blockNumber")),
        }
    return None


def _int_claim(value: object, default: int = 0) -> int:
    if isinstance(value, bool):
        return default
    if isinstance(value, int):
        return value
    if isinstance(value, float) and value.is_integer():
        return int(value)
    if isinstance(value, str):
        try:
            return int(value, 10)
        except ValueError:
            return default
    return default


