def _client_ip() -> str:
    forwarded = request.headers.get("x-forwarded-for", "")
    if forwarded:
        return forwarded.split(",", 1)[0].strip().lower()
    real = request.headers.get("x-real-ip", "")
    if real:
        return real.strip().lower()
    return (request.remote_addr or "").replace("::ffff:", "").lower()


