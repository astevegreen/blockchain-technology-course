def _wait_for_instructor_metadata(timeout_seconds: int = 30) -> bool:
    deadline = time.time() + timeout_seconds
    while True:
        _refresh_pool()
        _refresh_runtime_config()
        if _metadata_ready():
            return True
        if time.time() >= deadline:
            return False
        time.sleep(1)


