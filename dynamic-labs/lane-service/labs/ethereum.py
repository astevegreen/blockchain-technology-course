@blueprint.route("/api/ethereum/arcade/session", methods=["POST"])
def ethereum_arcade_session():
    session_uuid, station, error = _require_active_session()
    if error:
        body, status = error
        return jsonify(body), status
    assert session_uuid and station

    cfg = _runtime_config()
    vault = _normalize_address(cfg.get("arcadeVaultAddress"))
    if not vault:
        return jsonify({"ok": False, "error": "arcade vault is not configured"}), 409

    body = request.get_json(silent=True) or {}
    tx_hash = str(body.get("txHash") or "").strip().lower()
    if not _TX_HASH_RE.match(tx_hash):
        return jsonify({"ok": False, "error": "valid txHash required"}), 400
    requested_wallet = _normalize_address(body.get("address"))
    expected_wallet = requested_wallet or _active_wallet_address(session_uuid)
    if not expected_wallet:
        return jsonify({"ok": False, "error": "wallet address required"}), 400

    now = int(time.time())
    with _arcade_lock:
        state = _load_arcade_state()
        existing_key = (state.get("txSessions") or {}).get(tx_hash)
        existing = (state.get("consumedSessions") or {}).get(existing_key or "")
        if existing:
            if int(existing.get("exp") or 0) > now and existing.get("token"):
                return jsonify({
                    "ok": True,
                    "token": existing["token"],
                    "game": existing.get("gameId"),
                    "exp": existing.get("exp"),
                    "session": {k: v for k, v in existing.items() if k != "token"},
                    "idempotent": True,
                })
            return jsonify({"ok": False, "error": "arcade session already consumed"}), 409

    try:
        receipt = _json_rpc("eth_getTransactionReceipt", [tx_hash])
    except Exception as exc:
        return jsonify({"ok": False, "error": f"could not verify transaction: {exc}"}), 502
    if not receipt:
        return jsonify({"ok": False, "error": "transaction is not mined yet"}), 409
    if _hex_int(receipt.get("status")) != 1:
        return jsonify({"ok": False, "error": "transaction did not succeed"}), 409

    decoded = _decode_arcade_session_log(receipt, vault)
    if not decoded:
        return jsonify({"ok": False, "error": "transaction did not start an arcade session"}), 409
    if decoded.get("player") != expected_wallet:
        return jsonify({"ok": False, "error": "arcade session belongs to a different wallet"}), 403

    try:
        latest_block = _hex_int(_json_rpc("eth_blockNumber", []))
    except Exception:
        latest_block = decoded.get("blockNumber") or 0
    if latest_block and decoded.get("blockNumber") and latest_block - int(decoded["blockNumber"]) > ARCADE_MAX_RECEIPT_BLOCK_AGE:
        return jsonify({"ok": False, "error": "arcade session transaction is too old"}), 409

    key = f"{decoded['player']}:{decoded['nonce']}"
    iat = now
    exp = iat + ARCADE_SESSION_TTL_SECONDS
    claims = {
        "sid": session_uuid,
        "sub": decoded["player"],
        "game": decoded["gameId"],
        "nonce": decoded["nonce"],
        "iat": iat,
        "exp": exp,
    }
    token = _sign_arcade_token(claims)
    record = {
        "sessionUuid": session_uuid,
        "station": station,
        "player": decoded["player"],
        "gameId": decoded["gameId"],
        "nonce": decoded["nonce"],
        "timestamp": decoded["timestamp"],
        "txHash": tx_hash,
        "blockNumber": decoded.get("blockNumber"),
        "issuedAt": _utc_now(),
        "iat": iat,
        "exp": exp,
        "token": token,
    }

    with _arcade_lock:
        state = _load_arcade_state()
        consumed = state.setdefault("consumedSessions", {})
        tx_sessions = state.setdefault("txSessions", {})
        if key in consumed:
            return jsonify({"ok": False, "error": "arcade session already consumed"}), 409
        consumed[key] = record
        tx_sessions[tx_hash] = key
        recent = state.setdefault("recentSessions", [])
        recent.append(record)
        state["recentSessions"] = recent[-80:]
        _save_arcade_state(state)

    return jsonify({
        "ok": True,
        "token": token,
        "game": decoded["gameId"],
        "exp": exp,
        "session": {k: v for k, v in record.items() if k != "token"},
    })


@blueprint.route("/api/ethereum/arcade/score", methods=["POST"])
def ethereum_arcade_score():
    session_uuid, station, error = _require_active_session()
    if error:
        body, status = error
        return jsonify(body), status
    assert session_uuid and station

    body = request.get_json(silent=True) or {}
    if not isinstance(body, dict):
        return jsonify({"ok": False, "error": "JSON object required"}), 400

    token = str(body.get("token") or "").strip()
    try:
        claims = _verify_arcade_token(token)
    except ValueError as exc:
        return jsonify({"ok": False, "error": str(exc)}), 401

    now = int(time.time())
    claim_session = str(claims.get("sid") or "").strip().lower()
    claim_player = _normalize_address(claims.get("sub"))
    claim_game_id = _int_claim(claims.get("game"))
    claim_nonce = _int_claim(claims.get("nonce"))
    claim_exp = _int_claim(claims.get("exp"))
    requested_session = str(body.get("sessionId") or "").strip().lower()
    active_wallet = _active_wallet_address(session_uuid)

    if claim_session != session_uuid or (requested_session and requested_session != session_uuid):
        return jsonify({"ok": False, "error": "signed arcade pass belongs to a different session"}), 403
    if not claim_player or (active_wallet and claim_player != active_wallet):
        return jsonify({"ok": False, "error": "signed arcade pass belongs to a different wallet"}), 403
    if claim_exp <= now:
        return jsonify({"ok": False, "error": "signed arcade pass has expired"}), 409

    game_id = _int_claim(body.get("gameId"))
    nonce = _int_claim(body.get("nonce"))
    score = _int_claim(body.get("score"), -1)
    elapsed_ms = _int_claim(body.get("elapsedMs"), -1)
    outcome = str(body.get("outcome") or "complete").strip()[:32]
    if not re.fullmatch(r"[A-Za-z0-9_-]{1,32}", outcome):
        outcome = "complete"
    tx_hash = str(body.get("txHash") or "").strip().lower()
    if tx_hash and not _TX_HASH_RE.match(tx_hash):
        return jsonify({"ok": False, "error": "valid txHash required"}), 400
    if game_id != claim_game_id or nonce != claim_nonce:
        return jsonify({"ok": False, "error": "score payload does not match the signed arcade pass"}), 403
    if game_id <= 0 or nonce <= 0:
        return jsonify({"ok": False, "error": "valid gameId and nonce required"}), 400
    if score <= 0 or score > 1_000_000:
        return jsonify({"ok": False, "error": "score must be between 1 and 1,000,000"}), 400
    if elapsed_ms < 0 or elapsed_ms > (ARCADE_SESSION_TTL_SECONDS + 30) * 1000:
        return jsonify({"ok": False, "error": "elapsedMs is outside the active session window"}), 400

    key = f"{claim_player}:{nonce}"
    result_payload = {
        "player": claim_player,
        "gameId": game_id,
        "nonce": nonce,
        "score": score,
        "elapsedMs": elapsed_ms,
        "outcome": outcome,
    }
    result_hash = _arcade_result_hash(result_payload)
    token_hash = hashlib.sha256(token.encode("utf-8")).hexdigest()

    with _arcade_lock:
        state = _load_arcade_state()
        consumed = state.setdefault("consumedSessions", {})
        session_record = consumed.get(key)
        if not session_record:
            return jsonify({"ok": False, "error": "signed arcade pass was not issued for this session"}), 409
        if session_record.get("token") and not hmac.compare_digest(str(session_record.get("token")), token):
            return jsonify({"ok": False, "error": "signed arcade pass token does not match the issued session"}), 403
        if str(session_record.get("sessionUuid") or "").lower() != session_uuid:
            return jsonify({"ok": False, "error": "issued arcade pass belongs to a different session"}), 403
        if _normalize_address(session_record.get("player")) != claim_player:
            return jsonify({"ok": False, "error": "issued arcade pass belongs to a different wallet"}), 403
        if _int_claim(session_record.get("gameId")) != game_id or _int_claim(session_record.get("nonce")) != nonce:
            return jsonify({"ok": False, "error": "issued arcade pass does not match this score"}), 403
        if _int_claim(session_record.get("exp")) <= now:
            return jsonify({"ok": False, "error": "issued arcade pass has expired"}), 409

        submissions = state.setdefault("scoreSubmissions", {})
        existing = submissions.get(key)
        if existing:
            if existing.get("resultHash") != result_hash:
                return jsonify({"ok": False, "error": "this arcade session already locked a different score"}), 409
            if tx_hash:
                existing_tx = str(existing.get("txHash") or "").lower()
                if existing_tx and existing_tx != tx_hash:
                    return jsonify({"ok": False, "error": "this arcade session already has a different score transaction"}), 409
                existing["txHash"] = tx_hash
                existing["status"] = "tx-sent"
                existing["txRecordedAt"] = _utc_now()
                _save_arcade_state(state)
            return jsonify({
                "ok": True,
                "idempotent": True,
                "player": claim_player,
                "gameId": game_id,
                "nonce": nonce,
                "score": score,
                "elapsedMs": elapsed_ms,
                "outcome": outcome,
                "txHash": existing.get("txHash") or tx_hash,
                "resultHash": result_hash,
            })

        attempt = {
            "sessionUuid": session_uuid,
            "station": station,
            "player": claim_player,
            "gameId": game_id,
            "nonce": nonce,
            "score": score,
            "elapsedMs": elapsed_ms,
            "outcome": outcome,
            "status": "validated",
            "validatedAt": _utc_now(),
            "exp": claim_exp,
            "tokenHash": token_hash,
            "resultHash": result_hash,
        }
        if tx_hash:
            attempt["txHash"] = tx_hash
            attempt["status"] = "tx-sent"
            attempt["txRecordedAt"] = _utc_now()
        submissions[key] = attempt
        recent = state.setdefault("recentScoreAttempts", [])
        recent.append(attempt)
        state["recentScoreAttempts"] = recent[-120:]
        _save_arcade_state(state)

    return jsonify({
        "ok": True,
        "player": claim_player,
        "gameId": game_id,
        "nonce": nonce,
        "score": score,
        "elapsedMs": elapsed_ms,
        "outcome": outcome,
        "txHash": tx_hash,
        "resultHash": result_hash,
    })


