def _read_json(path: Path, default: Any) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return default


def _write_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    tmp.replace(path)


def _b64url(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode("ascii")


def _b64url_decode(value: str) -> bytes:
    padding = "=" * (-len(value) % 4)
    return base64.urlsafe_b64decode((value + padding).encode("ascii"))


def _arcade_secret() -> bytes:
    env_secret = os.environ.get("ARCADE_JWT_SECRET", "").strip()
    if env_secret:
        return env_secret.encode("utf-8")
    try:
        return _arcade_secret_path.read_text(encoding="utf-8").strip().encode("utf-8")
    except OSError:
        _arcade_secret_path.parent.mkdir(parents=True, exist_ok=True)
        secret = secrets.token_urlsafe(48)
        _arcade_secret_path.write_text(secret + "\n", encoding="utf-8")
        return secret.encode("utf-8")


def _sign_arcade_token(claims: dict) -> str:
    header = {"alg": "HS256", "typ": "JWT"}
    h = _b64url(json.dumps(header, separators=(",", ":"), sort_keys=True).encode("utf-8"))
    p = _b64url(json.dumps(claims, separators=(",", ":"), sort_keys=True).encode("utf-8"))
    sig = hmac.new(_arcade_secret(), f"{h}.{p}".encode("ascii"), hashlib.sha256).digest()
    return f"{h}.{p}.{_b64url(sig)}"


def _verify_arcade_token(token: str) -> dict:
    parts = str(token or "").strip().split(".")
    if len(parts) != 3:
        raise ValueError("signed arcade pass is malformed")
    header_raw, payload_raw, signature_raw = parts
    expected = hmac.new(_arcade_secret(), f"{header_raw}.{payload_raw}".encode("ascii"), hashlib.sha256).digest()
    if not hmac.compare_digest(_b64url(expected), signature_raw):
        raise ValueError("signed arcade pass is invalid")
    try:
        header = json.loads(_b64url_decode(header_raw).decode("utf-8"))
        claims = json.loads(_b64url_decode(payload_raw).decode("utf-8"))
    except Exception as exc:
        raise ValueError("signed arcade pass cannot be decoded") from exc
    if not isinstance(header, dict) or header.get("alg") != "HS256":
        raise ValueError("signed arcade pass uses an unsupported algorithm")
    if not isinstance(claims, dict):
        raise ValueError("signed arcade pass has invalid claims")
    return claims


def _json_rpc(method: str, params: list[Any]) -> Any:
    payload = json.dumps({"jsonrpc": "2.0", "id": int(time.time() * 1000) % 1_000_000, "method": method, "params": params}).encode("utf-8")
    req = Request(ARCADE_RPC_URL, data=payload, headers={"Content-Type": "application/json"})
    with urlopen(req, timeout=10) as r:
        doc = json.loads(r.read().decode("utf-8"))
    if not isinstance(doc, dict):
        raise RuntimeError("invalid JSON-RPC response")
    if doc.get("error"):
        message = doc["error"].get("message") if isinstance(doc["error"], dict) else str(doc["error"])
        raise RuntimeError(message or f"JSON-RPC {method} failed")
    return doc.get("result")


def _hex_int(value: object, default: int = 0) -> int:
    if isinstance(value, str):
        try:
            return int(value, 16) if value.startswith("0x") else int(value)
        except ValueError:
            return default
    if isinstance(value, int):
        return value
    return default


def _coerce_arcade_state(doc: object) -> dict:
    if not isinstance(doc, dict):
        return {"consumedSessions": {}, "txSessions": {}, "recentSessions": [], "scoreSubmissions": {}, "recentScoreAttempts": []}
    consumed = doc.get("consumedSessions") if isinstance(doc.get("consumedSessions"), dict) else {}
    tx_sessions = doc.get("txSessions") if isinstance(doc.get("txSessions"), dict) else {}
    recent = doc.get("recentSessions") if isinstance(doc.get("recentSessions"), list) else []
    score_submissions = doc.get("scoreSubmissions") if isinstance(doc.get("scoreSubmissions"), dict) else {}
    recent_score_attempts = doc.get("recentScoreAttempts") if isinstance(doc.get("recentScoreAttempts"), list) else []
    return {
        "consumedSessions": {str(k): v for k, v in consumed.items() if isinstance(v, dict)},
        "txSessions": {str(k).lower(): str(v) for k, v in tx_sessions.items()},
        "recentSessions": [item for item in recent if isinstance(item, dict)][-80:],
        "scoreSubmissions": {str(k): v for k, v in score_submissions.items() if isinstance(v, dict)},
        "recentScoreAttempts": [item for item in recent_score_attempts if isinstance(item, dict)][-120:],
    }


