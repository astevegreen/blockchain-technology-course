def _release_nft_session(session_uuid: str) -> None:
    with _nft_lock:
        state = _load_nft_state()
        claims = state.get("claims") or {}
        batches = state.get("mintedBatches") or {}
        changed = False
        for slug, claim in list(claims.items()):
            if claim.get("sessionUuid") == session_uuid:
                claims.pop(slug, None)
                changed = True
        for key, batch in list(batches.items()):
            if key == session_uuid or batch.get("sessionUuid") == session_uuid:
                batches.pop(key, None)
                changed = True
        if changed:
            _save_nft_state(state)


