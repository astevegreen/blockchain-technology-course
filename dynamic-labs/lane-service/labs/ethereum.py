def _inspect_format(target: str, fmt: str) -> str:
    result = subprocess.run(
        ["docker", "inspect", "--format", fmt, target],
        capture_output=True,
        text=True,
        timeout=15,
    )
    if result.returncode != 0:
        raise RuntimeError((result.stderr or result.stdout).strip()[:300] or f"docker inspect failed for {target}")
    return result.stdout.strip()


def _inspect_env(target: str) -> dict[str, str]:
    raw = _inspect_format(target, "{{json .Config.Env}}")
    try:
        items = json.loads(raw)
    except ValueError:
        items = []
    env: dict[str, str] = {}
    for item in items if isinstance(items, list) else []:
        if not isinstance(item, str) or "=" not in item:
            continue
        key, value = item.split("=", 1)
        env[key] = value
    return env


def _ethereum_stale_container_probe(lane_id: str, container: str) -> tuple[bool, str]:
    """Recreate only this Ethereum lane when the shared image was rebuilt."""
    current_image_id = _inspect_format(IMAGE, "{{.Id}}")
    container_image_id = _inspect_format(container, "{{.Image}}")
    if current_image_id and container_image_id and current_image_id != container_image_id:
        return True, f"container image {container_image_id[:19]} != {IMAGE} {current_image_id[:19]}"
    entry = _pool_entry(lane_id, force=True)
    if entry:
        expected_address = _normalize_address(entry.get("address"))
        expected_private_key = str(entry.get("privateKey") or "").strip()
        env = _inspect_env(container)
        actual_address = _normalize_address(env.get("ASSIGNED_ADDRESS"))
        actual_private_key = str(env.get("ASSIGNED_PRIVATE_KEY") or "").strip()
        if expected_address and actual_address != expected_address:
            return True, f"assigned wallet {actual_address or 'missing'} != current pool {expected_address}"
        if expected_private_key and actual_private_key != expected_private_key:
            return True, "assigned private key differs from current pool"
    return False, "current image"


