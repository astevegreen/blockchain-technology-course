def _wallet_from_pool_entry(entry: Optional[dict], station: str) -> Optional[dict]:
    if not entry:
        return None
    address = _normalize_address(entry.get("address"))
    private_key = str(entry.get("privateKey") or "").strip()
    if not address or not _PRIVATE_KEY_RE.match(private_key):
        return None
    return {
        "id": "assigned",
        "address": address,
        "privateKey": private_key,
        "nickname": f"Station {station}",
        "source": "assigned",
        "poolId": str(entry.get("poolId") or ""),
        "poolGeneratedAt": str(entry.get("poolGeneratedAt") or ""),
        "createdAt": _utc_now(),
    }


def _upsert_assigned_wallet(wallets: dict, assigned: dict) -> tuple[dict, bool, bool]:
    items = wallets.get("wallets") if isinstance(wallets.get("wallets"), list) else []
    items = [item for item in items if isinstance(item, dict)]
    existing = next(
        (item for item in items if item.get("id") == "assigned" or item.get("source") == "assigned"),
        None,
    )
    changed = False
    assigned_changed = False
    if existing:
        for key in ("id", "address", "privateKey", "nickname", "source", "poolId", "poolGeneratedAt"):
            if existing.get(key) != assigned.get(key):
                existing[key] = assigned.get(key)
                changed = True
                assigned_changed = True
        if existing.get("createdAt") is None:
            existing["createdAt"] = assigned.get("createdAt")
            changed = True
    else:
        items.insert(0, assigned)
        changed = True
        assigned_changed = True

    active_id = wallets.get("activeId")
    active_exists = any(item.get("id") == active_id for item in items)
    next_active_id = "assigned" if assigned_changed or not active_id or not active_exists else active_id
    if wallets.get("activeId") != next_active_id:
        wallets["activeId"] = next_active_id
        changed = True

    wallets["wallets"] = items
    return wallets, changed, assigned_changed


def _sync_nft_session_wallet(session_uuid: str, station: str, assigned: dict) -> None:
    owner = _normalize_address(assigned.get("address"))
    if not owner:
        return
    changed = False
    with _nft_lock:
        state = _load_nft_state()
        for claim in state["claims"].values():
            if claim.get("sessionUuid") != session_uuid:
                continue
            if claim.get("address") != owner:
                claim["address"] = owner
                changed = True
            if claim.get("station") != station:
                claim["station"] = station
                changed = True
        if changed:
            _save_nft_state(state)


def _init_session_state(session_uuid: str, station: str, resumed: bool = False) -> bool:
    assigned = _wallet_from_pool_entry(_pool_entry(station, force=True), station)
    assigned_changed = False
    with _session_lock:
        _session_dir(session_uuid).mkdir(parents=True, exist_ok=True)
        meta = _load_namespace(session_uuid, "meta")
        meta.update({
            "uuid": session_uuid,
            "station": station,
            "updatedAt": _utc_now(),
        })
        if not meta.get("createdAt"):
            meta["createdAt"] = _utc_now()
        if resumed:
            meta["resumedAt"] = _utc_now()
        _save_namespace(session_uuid, "meta", meta)

        if assigned:
            wallets = _load_namespace(session_uuid, "wallets")
            wallets, changed, assigned_changed = _upsert_assigned_wallet(wallets, assigned)
            if changed:
                _save_namespace(session_uuid, "wallets", wallets)
    if assigned:
        _sync_nft_session_wallet(session_uuid, station, assigned)
    return assigned_changed


def _wipe_session_state(session_uuid: str) -> None:
    with _session_lock:
        try:
            shutil.rmtree(_session_dir(session_uuid))
        except FileNotFoundError:
            pass


def _active_wallet(session_uuid: str) -> Optional[dict]:
    wallets = _load_namespace(session_uuid, "wallets")
    items = wallets.get("wallets") if isinstance(wallets.get("wallets"), list) else []
    active_id = wallets.get("activeId")
    active = next((item for item in items if item.get("id") == active_id), None) or (items[0] if items else None)
    return active if isinstance(active, dict) else None


def _active_wallet_address(session_uuid: str) -> str:
    active = _active_wallet(session_uuid)
    return _normalize_address(active.get("address")) if active else ""


def _claim_created(session_uuid: str, station: str, resumed: bool) -> None:
    assigned_changed = _init_session_state(session_uuid, station, resumed)
    if resumed and assigned_changed:
        # The instructor chain was likely redeployed and the station wallet pool
        # changed. Restart only this student's lane so its ASSIGNED_* env matches
        # the backend session wallet before the browser signs transactions.
        lane_manager.reset_lane(station, preserve_state=True)


def _claim_released(session_uuid: str, station: str, wipe: bool) -> None:
    _release_nft_session(session_uuid)
    _wipe_session_state(session_uuid)


def _coerce_nft_state(doc: object) -> dict:
    if not isinstance(doc, dict):
        return {"claims": {}, "mintedBatches": {}}

    raw_claims = doc.get("claims")
    if isinstance(raw_claims, list):
        claims = {
            str(claim.get("themeSlug") or "").strip(): claim
            for claim in raw_claims
            if isinstance(claim, dict) and str(claim.get("themeSlug") or "").strip()
        }
    elif isinstance(raw_claims, dict):
        claims = {
            str(slug).strip(): claim
            for slug, claim in raw_claims.items()
            if str(slug).strip() and isinstance(claim, dict)
        }
    else:
        claims = {}

    def _batch_key(batch: dict, fallback: object = "") -> str:
        session_uuid = str(batch.get("sessionUuid") or "").strip().lower()
        if _valid_uuid(session_uuid):
            return session_uuid
        return _normalize_address(fallback or batch.get("address"))

    raw_batches = doc.get("mintedBatches")
    if isinstance(raw_batches, list):
        batches = {
            _batch_key(batch): batch
            for batch in raw_batches
            if isinstance(batch, dict) and _batch_key(batch)
        }
    elif isinstance(raw_batches, dict):
        batches = {
            _batch_key(batch, address): batch
            for address, batch in raw_batches.items()
            if isinstance(batch, dict) and _batch_key(batch, address)
        }
    else:
        batches = {}

    for slug, claim in list(claims.items()):
        claim["themeSlug"] = str(claim.get("themeSlug") or slug).strip()
        claim["address"] = _normalize_address(claim.get("address"))
        claim["sessionUuid"] = str(claim.get("sessionUuid") or "").strip().lower()
        if not claim["address"] or not _valid_uuid(claim["sessionUuid"]):
            claims.pop(slug, None)

    for address, batch in list(batches.items()):
        batch["address"] = _normalize_address(batch.get("address") or address)
        batch["sessionUuid"] = str(batch.get("sessionUuid") or "").strip().lower()
        if not batch["address"] or not _valid_uuid(batch["sessionUuid"]):
            batches.pop(address, None)

    return {"claims": claims, "mintedBatches": batches}


def _load_nft_state() -> dict:
    try:
        doc = json.loads(_nft_state_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        doc = {}
    return _coerce_nft_state(doc)


def _save_nft_state(state: dict) -> None:
    STATE_DIR.mkdir(parents=True, exist_ok=True)
    tmp = _nft_state_path.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(state, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    tmp.replace(_nft_state_path)


def _nft_state_payload(state: dict) -> dict:
    claims = state.get("claims") or {}
    batches = state.get("mintedBatches") or {}
    return {
        "claims": sorted(claims.values(), key=lambda item: item.get("at", "")),
        "mintedBatches": sorted(batches.values(), key=lambda item: item.get("at", "")),
    }


def _fetch_json(url: str) -> Optional[dict]:
    try:
        with urlopen(url, timeout=5) as r:
            doc = json.loads(r.read().decode("utf-8"))
    except (URLError, OSError, ValueError):
        return None
    return doc if isinstance(doc, dict) else None


