"""
Ethereum lab -- on-demand per-student frontend lanes against a shared
instructor-run hardhat chain.

Architecture differs from bitcoin:
- The blockchain itself is shared. There's exactly one hardhat node,
  inside the long-running `ethereum-trainer-instructor` container, and
  every student SPA submits transactions through the platform router at
  `/labs/ethereum_lab/rpc-write` (which hits the instructor's in-container
  write-filtered proxy). Reads come from cache endpoints.
- Each student gets a thin lane container (same image, MODE=student)
  that serves the SPA + lab-API + ttyd PTY. No hardhat node per lane.
- A capacity-sized address pool, generated by the instructor on startup and
  pre-funded on the shared chain, is partitioned by station number. The lane's
  env carries ASSIGNED_ADDRESS / ASSIGNED_PRIVATE_KEY so the SPA can pre-load
  the wallet without a per-student race. Instructor restarts rotate the pool by
  default, so station wallets do not retain on-chain history across chain resets.

Routing (see router/routes/ethereum.conf):
  /labs/ethereum_lab/                -- claim -> cookie -> resolve to lane :5173
  /labs/ethereum_lab/rpc-write       -- ungated -> instructor :8080/rpc-write
  /labs/ethereum_lab/instructor/...  -- cookie-gated -> instructor :8080
"""

