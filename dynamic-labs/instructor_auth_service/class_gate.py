"""Class gate: one class code per class, and the signed class pass it buys.

A cloud class host is on the open internet, so student pages sit behind a
class code. The instructor reads the code next to their credentials
(`.runtime/instructor-credentials.txt`) or in the instructor portal, where they
can also change it. A student who enters the code gets a signed `class_pass`
cookie; the router (`router/routes/_class_gate.conf`) and the lane-service
(`/claim`, `/resolve`) ask `/api/class/verify` whether a request carries one.

The pass holds a keyed fingerprint of the code it was issued for, so changing
the code voids every pass issued before the change. A valid instructor cookie
passes the gate too.

The code lives in `CLASS_CODE` (generated by `runtime-credentials.sh`) until
the instructor changes it in the portal; the change is written to
`CLASS_GATE_STATE_DIR/class-code.json` so both gunicorn workers and a restart
see it. A redeploy that rotates `CLASS_CODE` wins over an older portal change.
"""

from __future__ import annotations

import hashlib
import hmac
import ipaddress
import json
import os
import re
import secrets
import tempfile
import threading
import time
from pathlib import Path

from itsdangerous import BadSignature, SignatureExpired, URLSafeTimedSerializer


PASS_COOKIE_NAME = "class_pass"
PASS_SALT = "class-pass-v1"
PASS_MAX_AGE = 14 * 24 * 3600
RETURN_TO_COOKIE_NAME = "class_return_to"
RETURN_TO_SALT = "class-return-to-v1"
RETURN_TO_MAX_AGE = 15 * 60
RETURN_TO_MAX_LENGTH = 2048

# No 0/O or 1/I/L: the code is read off a projector and typed by hand.
CODE_ALPHABET = "ABCDEFGHJKMNPQRSTUVWXYZ23456789"
GENERATED_LENGTH = 8
MIN_LENGTH = 6
MAX_LENGTH = 32
_CODE_RE = re.compile(r"^[A-Z0-9]+$")

# The lab subdomains (router/nginx-*.conf) share the main host's pass.
LAB_HOST_PREFIXES = ("explorer.", "tokens.", "dex-l2.", "dex.")

STATE_FILE_NAME = "class-code.json"
DEFAULT_STATE_DIR = "/var/lib/class-gate"

_lock = threading.Lock()


def gate_enabled() -> bool:
    return (os.environ.get("CLASS_GATE") or "off").strip().lower() in {"1", "on", "true", "yes"}


def normalize_code(raw: str) -> str:
    """Upper-case and drop spaces and dashes, so "abcd-efgh" matches "ABCDEFGH"."""
    return re.sub(r"[\s-]+", "", str(raw or "")).upper()


def code_problem(code: str) -> str | None:
    """Why `code` (already normalized) can't be a class code, or None."""
    if len(code) < MIN_LENGTH or len(code) > MAX_LENGTH:
        return f"the class code must be {MIN_LENGTH} to {MAX_LENGTH} letters or digits"
    if not _CODE_RE.match(code):
        return "the class code may hold only letters and digits"
    return None


def generate_code() -> str:
    return "".join(secrets.choice(CODE_ALPHABET) for _ in range(GENERATED_LENGTH))


def _state_path() -> Path:
    return Path(os.environ.get("CLASS_GATE_STATE_DIR") or DEFAULT_STATE_DIR) / STATE_FILE_NAME


def _deploy_code() -> str:
    code = normalize_code(os.environ.get("CLASS_CODE", ""))
    return "" if code_problem(code) else code


def _deploy_fingerprint() -> str:
    return hashlib.sha256(_deploy_code().encode("utf-8")).hexdigest()[:16]


def current_code() -> tuple[str, str]:
    """The class code in force and where it came from ("portal", "deploy" or "none")."""
    try:
        state = json.loads(_state_path().read_text(encoding="utf-8"))
    except (OSError, ValueError):
        state = None
    if isinstance(state, dict) and state.get("base") == _deploy_fingerprint():
        code = normalize_code(state.get("code", ""))
        if not code_problem(code):
            return code, "portal"
    code = _deploy_code()
    return (code, "deploy") if code else ("", "none")


def set_code(code: str) -> None:
    """Make `code` (already normalized and valid) the class code; old passes stop working."""
    path = _state_path()
    payload = {"code": code, "base": _deploy_fingerprint(), "changed_at": int(time.time())}
    with _lock:
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(prefix=".class-code.", dir=str(path.parent))
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as fh:
                json.dump(payload, fh)
            os.replace(tmp, path)
        except BaseException:
            try:
                os.unlink(tmp)
            except OSError:
                pass
            raise


def codes_match(submitted: str, code: str) -> bool:
    if not code:
        return False
    return hmac.compare_digest(normalize_code(submitted).encode("utf-8"), code.encode("utf-8"))


def _fingerprint(secret: str, code: str) -> str:
    return hmac.new(secret.encode("utf-8"), f"class-code:{code}".encode("utf-8"), hashlib.sha256).hexdigest()[:32]


def _serializer(secret: str, salt: str) -> URLSafeTimedSerializer:
    return URLSafeTimedSerializer(secret, salt=salt)


def mint_pass(secret: str, code: str) -> str:
    return _serializer(secret, PASS_SALT).dumps({"v": 1, "fp": _fingerprint(secret, code)})


def pass_is_valid(secret: str, token: str | None, code: str) -> bool:
    """True when `token` is a class pass issued for the class code in force."""
    if not token or not code:
        return False
    try:
        data = _serializer(secret, PASS_SALT).loads(token, max_age=PASS_MAX_AGE)
    except (BadSignature, SignatureExpired):
        return False
    if not isinstance(data, dict):
        return False
    return hmac.compare_digest(str(data.get("fp") or ""), _fingerprint(secret, code))


def cookie_domain(host: str) -> str | None:
    """The Domain for the pass cookie, so the lab subdomains accept it.

    `CLASS_PASS_COOKIE_DOMAIN` wins. Otherwise a host name with a dot gets its
    lab-subdomain prefix stripped ("explorer.lab.example.org" -> "lab.example.org");
    an IP address or a single-label name ("localhost") gets a host-only cookie,
    which the browser already shares across the lab ports 8441-8444.
    """
    configured = (os.environ.get("CLASS_PASS_COOKIE_DOMAIN") or "").strip().lstrip(".")
    if configured:
        return configured
    name = (host or "").strip().lower()
    if name.startswith("["):
        return None
    name = name.rsplit(":", 1)[0] if name.count(":") == 1 else name
    if not name or "." not in name:
        return None
    try:
        ipaddress.ip_address(name)
        return None
    except ValueError:
        pass
    for prefix in LAB_HOST_PREFIXES:
        if name.startswith(prefix) and "." in name[len(prefix):]:
            return name[len(prefix):]
    return name


def safe_return_to(raw: str, *, method: str = "GET") -> str | None:
    """A same-site GET path to send the student back to after the code, or None."""
    target = (raw or "").strip()
    if method.upper() not in {"GET", "HEAD"}:
        return None
    if not target or len(target) > RETURN_TO_MAX_LENGTH:
        return None
    if any(ord(ch) < 32 or ord(ch) == 127 for ch in target):
        return None
    if not target.startswith("/") or target.startswith("//") or "\\" in target:
        return None
    path = target.split("?", 1)[0].split("#", 1)[0]
    if path in {"/class", "/class/"} or path.startswith("/class/"):
        return None
    # API calls are page fetches, not pages; a lab's claim link is the one exception.
    if path.startswith("/api/") and not path.endswith("/claim"):
        return None
    return target


def mint_return_to(secret: str, target: str) -> str:
    return _serializer(secret, RETURN_TO_SALT).dumps({"path": target})


def read_return_to(secret: str, token: str | None) -> str | None:
    if not token:
        return None
    try:
        data = _serializer(secret, RETURN_TO_SALT).loads(token, max_age=RETURN_TO_MAX_AGE)
    except (BadSignature, SignatureExpired):
        return None
    if not isinstance(data, dict):
        return None
    return safe_return_to(str(data.get("path") or ""))


class FailureLimiter:
    """Counts wrong class codes per client address.

    A whole class often shares one public address, so the limits are generous
    for typos and still far too slow to guess an 8-character code.
    """

    def __init__(self, limits: tuple[tuple[int, int], ...] = ((60, 20), (900, 100))) -> None:
        self.limits = limits
        self._hits: dict[str, list[float]] = {}
        self._mutex = threading.Lock()

    def _trim(self, ip: str, now: float) -> list[float]:
        horizon = max(window for window, _ in self.limits)
        hits = [t for t in self._hits.get(ip, []) if now - t < horizon]
        if hits:
            self._hits[ip] = hits
        else:
            self._hits.pop(ip, None)
        return hits

    def retry_after(self, ip: str) -> int:
        """Seconds until `ip` may try again; 0 when it may try now."""
        now = time.time()
        with self._mutex:
            hits = self._trim(ip, now)
            wait = 0
            for window, limit in self.limits:
                recent = [t for t in hits if now - t < window]
                if len(recent) >= limit:
                    wait = max(wait, int(window - (now - recent[-limit])) + 1)
            return wait

    def record_failure(self, ip: str) -> None:
        now = time.time()
        with self._mutex:
            hits = self._trim(ip, now)
            hits.append(now)
            self._hits[ip] = hits
            if len(self._hits) > 4096:
                for stale in list(self._hits)[:1024]:
                    self._hits.pop(stale, None)
