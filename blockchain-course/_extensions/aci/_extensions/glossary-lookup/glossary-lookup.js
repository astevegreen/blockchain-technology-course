/* glossary-lookup.js: look up a course term without leaving the slide.
   The corner button or the G key opens a search panel over the slide; a word selected on the slide is searched for.
   Term and alias matches list first; matches inside definitions sit below, collapsed behind
   "Also mentioned in N definitions". Each definition links to the slide that teaches the term.
   Data: <site root>/glossary/terms.json, generated by the glossary pipeline (glossary/README.md).
   The pure parts (normalize, variants, buildIndex, search, siteRoot, highlighter) are tested in
   tools/tests/glossary_lookup.test.mjs. */
(function (global) {
  "use strict";

  const MAX_SELECTION = 60; // a longer selection is a sentence, not a term: open the panel empty
  const MAX_SHOWN = 50;     // per group; typing more narrows the list
  const MIN_QUERY = 2;

  function normalize(text) {
    return String(text || "")
      .normalize("NFKD").replace(/[̀-ͯ]/g, "")
      .toLowerCase()
      .replace(/[‘’]/g, "'").replace(/[“”]/g, '"')
      .replace(/\s+/g, " ").trim();
  }

  // The query and the singular of its last word, so "transactions" finds "Transaction".
  function variants(query) {
    const q = normalize(query);
    if (q.length < MIN_QUERY) return [];
    const out = [q];
    const last = q.split(" ").pop();
    if (last.length > 3) {
      const stem = q.slice(0, q.length - last.length);
      if (last.endsWith("ies")) out.push(stem + last.slice(0, -3) + "y");
      else if (/(ses|xes|ches|shes)$/.test(last)) out.push(stem + last.slice(0, -2));
      if (last.endsWith("s") && !last.endsWith("ss")) out.push(stem + last.slice(0, -1));
    }
    return [...new Set(out)];
  }

  function escapeRegExp(text) {
    return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  }

  function wordStart(text) {
    return new RegExp("(^|[^a-z0-9])" + escapeRegExp(text));
  }

  function buildIndex(terms) {
    return (terms || []).map((term) => ({
      term,
      display: normalize(term.display),
      names: [term.display, ...(term.aliases || [])].map(normalize),
      definition: normalize(term.definition),
    }));
  }

  // Lower is better: exact, then starts with, then a word starts with, then contains; a display-name match beats
  // the same kind of alias match.
  function nameScore(entry, patterns) {
    let best = Infinity;
    entry.names.forEach((name, n) => {
      for (const p of patterns) {
        let kind;
        if (name === p.text) kind = 0;
        else if (name.startsWith(p.text)) kind = 1;
        else if (p.wordStart.test(name)) kind = 2;
        else if (name.includes(p.text)) kind = 3;
        else continue;
        best = Math.min(best, kind * 2 + (n === 0 ? 0 : 1));
      }
    });
    return best;
  }

  // { names: terms whose name or alias matches, best first; definitions: other terms whose definition holds a
  // word starting with the query, A to Z }.
  function search(index, query) {
    const patterns = variants(query).map((text) => ({ text, wordStart: wordStart(text) }));
    if (!patterns.length) return { names: [], definitions: [] };
    const named = [];
    const defined = [];
    for (const entry of index) {
      const score = nameScore(entry, patterns);
      if (score < Infinity) named.push({ entry, score });
      else if (patterns.some((p) => p.wordStart.test(entry.definition))) defined.push(entry);
    }
    named.sort((a, b) => a.score - b.score
      || a.entry.display.length - b.entry.display.length
      || a.entry.display.localeCompare(b.entry.display));
    defined.sort((a, b) => a.display.localeCompare(b.display));
    return { names: named.map((x) => x.entry.term), definitions: defined.map((e) => e.term) };
  }

  // The site root from a lesson's address: lessons live at <root>lessons/<section>/<file>.html.
  function siteRoot(href) {
    const url = new URL(href);
    url.hash = "";
    url.search = "";
    const at = url.pathname.lastIndexOf("/lessons/");
    url.pathname = at >= 0 ? url.pathname.slice(0, at + 1) : url.pathname.replace(/[^/]*$/, "");
    return url.href;
  }

  // A case-blind pattern for the query's variants, longest first, for <mark>ing them in the panel.
  function highlighter(query) {
    const vs = variants(query).sort((a, b) => b.length - a.length);
    return vs.length ? new RegExp(vs.map(escapeRegExp).join("|"), "gi") : null;
  }

  // ---- the panel ------------------------------------------------------------------------------------------------
  function el(tag, className, text) {
    const node = document.createElement(tag);
    if (className) node.className = className;
    if (text !== undefined) node.textContent = text;
    return node;
  }

  function appendMarked(node, text, pattern) {
    if (!pattern) {
      node.textContent = text;
      return node;
    }
    let last = 0;
    for (const m of text.matchAll(pattern)) {
      if (!m[0]) continue;
      node.append(text.slice(last, m.index), el("mark", "", m[0]));
      last = m.index + m[0].length;
    }
    node.append(text.slice(last));
    return node;
  }

  function selectedText() {
    const text = String(global.getSelection ? global.getSelection() : "").replace(/\s+/g, " ").trim();
    return text.length <= MAX_SELECTION ? text : "";
  }

  const BOOK_ICON =
    '<svg viewBox="0 0 24 24" width="22" height="22" fill="none" stroke="currentColor" stroke-width="2"' +
    ' stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' +
    '<path d="M4 19.5A2.5 2.5 0 0 1 6.5 17H20"/>' +
    '<path d="M6.5 2H20v20H6.5A2.5 2.5 0 0 1 4 19.5v-15A2.5 2.5 0 0 1 6.5 2z"/>' +
    '<path d="M9 7h7M9 11h5"/></svg>';

  function GlossaryLookup() {
    return {
      id: "GlossaryLookup",
      init(deck) {
        const params = new URLSearchParams(global.location.search);
        // Speaker-view previews and PDF export get no panel.
        if (params.has("receiver") || params.has("print-pdf")) return;

        const root = siteRoot(global.location.href);
        const termsUrl = root + "glossary/terms.json";
        let index = null;
        let loading = null;

        const dialog = el("dialog", "glossary-lookup");
        dialog.setAttribute("aria-labelledby", "glossary-lookup-title");
        const head = el("div", "gl-head");
        const title = el("h2", "gl-title", "Glossary");
        title.id = "glossary-lookup-title";
        const close = el("button", "gl-close", "×");
        close.type = "button";
        close.setAttribute("aria-label", "Close the glossary");
        head.append(title, close);
        const input = el("input", "gl-input");
        input.type = "search";
        input.placeholder = "Look up a term";
        input.setAttribute("aria-label", "Look up a term");
        input.autocomplete = "off";
        input.spellcheck = false;
        const status = el("p", "gl-status");
        status.setAttribute("aria-live", "polite");
        const body = el("div", "gl-body");
        const list = el("ol", "gl-list");
        const more = el("details", "gl-more");
        const summary = el("summary");
        const moreList = el("ol", "gl-list");
        more.append(summary, moreList);
        body.append(list, more);
        const foot = el("p", "gl-foot");
        const full = el("a", "", "Full glossary");
        full.href = root + "glossary/index.html";
        full.target = "_blank";
        full.rel = "noopener";
        foot.append(full, " (new tab) · Esc closes");
        dialog.append(head, input, status, body, foot);
        document.body.appendChild(dialog);

        const button = el("button", "glossary-lookup-button");
        button.type = "button";
        button.title = "Glossary (G)";
        button.setAttribute("aria-label", "Open the glossary (G)");
        button.innerHTML = BOOK_ICON;
        document.body.appendChild(button);

        function load() {
          if (!loading) {
            loading = fetch(termsUrl)
              .then((r) => {
                if (!r.ok) throw new Error("HTTP " + r.status);
                return r.json();
              })
              .then((data) => {
                index = buildIndex(data.terms);
              })
              .catch((err) => {
                loading = null;
                throw err;
              });
          }
          return loading;
        }

        function goTo(url, event) {
          if (url.pathname !== global.location.pathname) return; // another lesson: its link opens a new tab
          event.preventDefault();
          dialog.close();
          const id = decodeURIComponent(url.hash.replace(/^#\/?/, ""));
          const slide = id && document.getElementById(id);
          if (slide && slide.closest(".reveal .slides")) {
            const at = deck.getIndices(slide);
            deck.slide(at.h, at.v);
          } else {
            global.location.hash = url.hash;
          }
        }

        function item(term, pattern) {
          const li = el("li", "gl-term");
          li.append(appendMarked(el("h3", "gl-name"), term.display, pattern));
          if (term.aliases && term.aliases.length) {
            li.append(appendMarked(el("p", "gl-aliases"), "Also: " + term.aliases.join(", "), pattern));
          }
          li.append(appendMarked(el("p", "gl-def"), term.definition || "", pattern));
          const src = term.source || {};
          if (src.href) {
            const url = new URL(src.href, termsUrl);
            const link = el("a", "gl-source");
            link.href = url.href;
            const here = url.pathname === global.location.pathname;
            link.append("Taught on: ", el("span", "gl-slide", src.slide_heading || "its slide"),
              src.lesson_title ? " — " + src.lesson_title : "", here ? " (this lesson)" : " (new tab)");
            if (here) {
              link.addEventListener("click", (e) => goTo(url, e));
            } else {
              link.target = "_blank";
              link.rel = "noopener";
            }
            li.append(link);
          }
          return li;
        }

        function fill(target, terms, pattern) {
          terms.slice(0, MAX_SHOWN).forEach((t) => target.append(item(t, pattern)));
          if (terms.length > MAX_SHOWN) {
            target.append(el("li", "gl-cap", `${terms.length - MAX_SHOWN} more: type more of the term to narrow the list.`));
          }
        }

        function render() {
          const query = input.value;
          list.replaceChildren();
          moreList.replaceChildren();
          more.hidden = true;
          if (!index) {
            status.textContent = "Loading the glossary…";
            return;
          }
          if (normalize(query).length < MIN_QUERY) {
            status.textContent = "Type a term, or select a word on the slide and press G.";
            return;
          }
          const found = search(index, query);
          const pattern = highlighter(query);
          fill(list, found.names, pattern);
          const n = found.names.length;
          status.textContent = n ? `${n} term${n === 1 ? "" : "s"} named “${query.trim()}”`
            : `No term named “${query.trim()}”.`;
          const d = found.definitions.length;
          if (d) {
            summary.textContent = `Also mentioned in ${d} definition${d === 1 ? "" : "s"}`;
            fill(moreList, found.definitions, pattern);
            more.hidden = false;
            more.open = false; // opened on a click (build spec)
          }
          body.scrollTop = 0;
        }

        function open(query) {
          if (!dialog.open) dialog.showModal();
          if (query) input.value = query;
          input.focus();
          input.select();
          render();
          if (index) return;
          load().then(render, () => {
            status.replaceChildren("The glossary didn’t load. Use the ", full.cloneNode(true), " instead.");
          });
        }

        let timer = 0;
        input.addEventListener("input", () => {
          clearTimeout(timer);
          timer = setTimeout(render, 120);
        });
        close.addEventListener("click", () => dialog.close());
        // A click on the backdrop lands on the dialog itself.
        dialog.addEventListener("click", (e) => {
          if (e.target === dialog) dialog.close();
        });
        // Keys typed in the panel are not slide commands.
        ["keydown", "keypress", "keyup"].forEach((type) => dialog.addEventListener(type, (e) => e.stopPropagation()));
        // One Esc closes the panel; in a search box it would otherwise first clear the text.
        dialog.addEventListener("keydown", (e) => {
          if (e.key !== "Escape") return;
          e.preventDefault();
          dialog.close();
        });

        // A click clears the slide's selection in some browsers: read it on the press.
        let pressed = null;
        button.addEventListener("pointerdown", () => {
          pressed = selectedText();
        });
        button.addEventListener("click", () => {
          open(pressed === null ? selectedText() : pressed);
          pressed = null;
        });

        // Sit just right of the slide menu and chalkboard buttons in the bottom-left corner.
        // (offsetParent is always null for these fixed buttons, so visibility is read from their size.)
        function place() {
          const left = [".slide-chalkboard-buttons", ".slide-menu-button"]
            .map((s) => document.querySelector(s))
            .filter((n) => n && getComputedStyle(n).display !== "none" && n.getBoundingClientRect().width > 0)
            .reduce((x, n) => Math.max(x, n.getBoundingClientRect().right), 0);
          if (left > 0) button.style.left = Math.round(left + 6) + "px";
        }
        deck.on("ready", () => { place(); global.setTimeout(place, 500); });
        global.addEventListener("resize", place);

        // G replaces reveal.js's own G (jump to a slide number); the slide menu still jumps to any slide.
        // The help overlay lists a static "G: Jump to slide" row; rewrite that row and bind the key without
        // a `key`, so the overlay shows one G row, the glossary's.
        // reveal.js re-sets its static rows when it configures, so register again once it is ready.
        const relabel = () => deck.registerKeyboardShortcut("G", "Look up a term in the glossary");
        relabel();
        deck.on("ready", relabel);
        deck.addKeyBinding({ keyCode: 71, description: "Look up a term in the glossary" },
          () => open(selectedText()));
      },
    };
  }

  Object.assign(GlossaryLookup, { normalize, variants, buildIndex, search, siteRoot, highlighter });

  if (typeof module === "object" && module.exports) module.exports = GlossaryLookup;
  else global.GlossaryLookup = GlossaryLookup;
})(typeof window === "undefined" ? globalThis : window);
